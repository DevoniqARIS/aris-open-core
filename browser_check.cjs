// Requires Playwright for validation only; not needed to run the demo.
const { chromium } = require('playwright');
const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');
const project = path.resolve(__dirname,'../..');
const output = process.env.ARIS_BROWSER_OUTPUT || path.join(project,'validation','browser');
fs.mkdirSync(output,{recursive:true});
const py = process.env.ARIS_TEST_PYTHON || 'python';
const runtime = path.join(output,'runtime');
const server = spawn(py,['-c',`import uvicorn; from simulation.server import create_app; uvicorn.run(create_app(runtime=${JSON.stringify(runtime)},token='browser-validation-token',rate=4),host='127.0.0.1',port=8767,access_log=False)`],{cwd:project});
const errors=[];
let browser;
(async()=>{
 await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(new Error('Server startup timed out')),20000);server.stderr.on('data',data=>{if(data.toString().includes('Uvicorn running')){clearTimeout(timer);resolve()}});server.on('exit',code=>reject(new Error('Server exited '+code)))});
 browser=await chromium.launch({...(process.env.ARIS_CHROMIUM?{executablePath:process.env.ARIS_CHROMIUM}:{}),headless:true,args:['--no-sandbox','--single-process','--no-zygote','--use-gl=angle','--use-angle=swiftshader']});
 const page=await browser.newPage({viewport:{width:1440,height:1200},acceptDownloads:true});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8767/#token=browser-validation-token');
 await page.waitForFunction(()=>document.getElementById('camera').naturalWidth>0);
 await page.screenshot({path:path.join(output,'ready.png'),fullPage:true});
 await page.click('#record');await page.click('#start');
 await page.waitForFunction(()=>document.getElementById('status').textContent==='RUNNING',{},{timeout:90000});
 console.log('Browser: actual mission running');
 await page.screenshot({path:path.join(output,'flight.png'),fullPage:true});
 await page.waitForFunction(()=>document.getElementById('status').textContent==='COMPLETE',{},{timeout:240000});
 await page.waitForFunction(()=>document.querySelectorAll('.evidence-card').length===6);
 if(!(await page.textContent('#verdict')).includes('PASS'))throw new Error('Independent evaluator did not pass');
 const videoPromise=page.waitForEvent('download');await page.click('#record');const video=await videoPromise;await video.saveAs(path.join(output,'ARIS_live_simulation.webm'));
 const zipPromise=page.waitForEvent('download');await page.click('#export');const zip=await zipPromise;await zip.saveAs(path.join(output,'ARIS_measured_run.zip'));
 await page.screenshot({path:path.join(output,'complete.png'),fullPage:true});
 await page.click('.evidence-card');if(!await page.locator('#imageDialog').isVisible())throw new Error('Evidence dialog failed');await page.click('#closeDialog');
 const run=fs.readdirSync(path.join(runtime,'runs'))[0];
 await page.setInputFiles('#replayFile',path.join(runtime,'runs',run,'replay.json'));
 await page.waitForFunction(()=>document.getElementById('feedLabel').textContent==='RECORDED REPLAY');
 await page.click('#exitReplay');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
 if(overflow)throw new Error('Mobile horizontal overflow');
 if(errors.length)throw new Error('Browser errors: '+errors.join('; '));
 const result={status:'passed',browser:browser.version(),page_errors:errors,scenario:'occlusion',mission:'COMPLETE',oracle:'PASS',observations:6,recording_bytes:fs.statSync(path.join(output,'ARIS_live_simulation.webm')).size,export_bytes:fs.statSync(path.join(output,'ARIS_measured_run.zip')).size,mobile_overflow:overflow,checks:['3D WebGL page','live rendered camera','start actual mission','occlusion/reinspection','evidence gallery/dialog','WebM recording/download','run export','recorded replay','mobile layout']};
 fs.writeFileSync(path.join(output,'browser_results.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
})().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{if(browser)await browser.close();server.kill('SIGTERM')});
